#!/usr/bin/env node
// @ts-check
/// <reference types="node" />
// 构建 host.js：rolldown 把 host.ts 及其 `./lib/*` 依赖打成单文件 ESM，落在**包根**
// （与源码同目录，故 `import.meta.dirname` 的语义与源码态完全一致）。
// 编排（依赖段外部化、输出守卫、region 正典化、moduleIds 结构性判据）统一住在
// @jayyuen66/dsh-plugin-shared/lib/build-host，一处可改；本文件只声明本仓的入口、产物
// 与生成头。为什么必须有打包这一步、为什么外部化按包名段判——见 shared 同名切面的
// 文件头。
// 声明不在这儿产：`npm run build:types`（build-types.mjs）出 types/，`exports` 的 `.` 入口
// 同时挂 types/default。缺声明没有运行期信号，只有 import 本包的消费方在 strict 下拿 TS7016。
import path from "node:path";
import { rolldown } from "rolldown";
import { buildHostEntries } from "@jayyuen66/dsh-plugin-shared/lib/build-host";
import { invokedDirectly, writeArtifact } from "@jayyuen66/dsh-plugin-shared/lib/build-artifacts";

// 再导出：测试按「脚本自己导出它用的工具」这一口径导入（见 test/build-host.test.ts）。
export { singleEntryChunk } from "@jayyuen66/dsh-plugin-shared/lib/build-artifacts";

const root = import.meta.dirname;

/** 产物名（同一事实的三处表述——entries 的 output、find 的匹配串、写盘目标——共用它，
 *  改名漏一处会抛"清单里没有 host.js"或把别的产物写到 host.js 上）。 */
const HOST_ARTIFACT = "host.js";
/** 生成头的前缀（写盘自检判据；tests 里钉的是同一句）。 */
const GENERATED_PREFIX = "// GENERATED by build-host.mjs";

/** 生成 host.js 的完整文本。 */
export async function buildHost() {
  const artifacts = await buildHostEntries({
    root,
    rolldown,
    entries: [
      {
        source: "host.ts",
        output: HOST_ARTIFACT,
        header: `${GENERATED_PREFIX} — edit host.ts / lib/*.ts, then run \`node build-host.mjs\`.\n`,
      },
    ],
  });
  const artifact = artifacts.find((item) => item.output === HOST_ARTIFACT);
  if (artifact === undefined) {
    throw new Error(`buildHostEntries 交回的产物清单里没有 ${HOST_ARTIFACT}`);
  }
  return artifact.code;
}

async function main() {
  const out = await buildHost();
  // 写盘前自检：空正文或缺生成头说明构建返回了非预期输出——把它换成不可用产物且
  // 退出码还是 0，是最容易被误判成"构建通过"的失败形态。要写就写完整产物。
  if (out.length === 0 || !out.startsWith(GENERATED_PREFIX)) {
    throw new Error("host.js 构建产物异常（空正文或缺生成头），已放弃写盘");
  }
  await writeArtifact(path.join(root, HOST_ARTIFACT), out);
  console.info("host.js written:", Buffer.byteLength(out, "utf8"), "bytes");
}

if (invokedDirectly(import.meta.filename)) {
  try {
    await main();
  } catch (error) {
    console.error(error);
    process.exitCode = 1;
  }
}
