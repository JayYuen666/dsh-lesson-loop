#!/usr/bin/env node
// @ts-check
/// <reference types="node" />
// 构建 client.js：rolldown 把 src/client-entry.ts 打包为 CJS（外置清单精确匹配），再包进
// window.__ModuleLoader__.load({ id, factory }) UMD 外壳。id 取 package.json 的 name，
// 与 dsh.client 模块表键一致。
// 编排（外置判据、store 路径折叠、外壳拼装）统一住在 @jayyuen66/dsh-plugin-shared/
// lib/build-client；本文件只声明入口、生成头，以及本仓的外置清单口径（官方基座 + 本包
// `dsh.client.external` 声明）。运行：node build-client.mjs（或 npm run build:client）。
// buildClient() 与 clientExternals() 供测试导入。
import { readFile } from "node:fs/promises";
import path from "node:path";
import { rolldown } from "rolldown";
import { buildClientBundle } from "@jayyuen66/dsh-plugin-shared/lib/build-client";
import {
  asRecord,
  invokedDirectly,
  writeArtifact,
} from "@jayyuen66/dsh-plugin-shared/lib/build-artifacts";

// 再导出：测试按「脚本自己导出它用的工具」这一口径导入（见 test/build-client.test.ts）。
export { singleEntryChunk } from "@jayyuen66/dsh-plugin-shared/lib/build-artifacts";

const root = import.meta.dirname;

// 顶层读取带文件名上下文：裸 ENOENT/裸 SyntaxError 不告诉读者是哪份文件；解析结果
// 不是对象（顶层是数组/字符串）会静默退化成"只有基座的 external 清单"，一并拦下。
const pkgPath = path.join(root, "package.json");
/** @type {unknown} */
let pkgJson;
try {
  pkgJson = JSON.parse(await readFile(pkgPath, "utf8"));
} catch (error) {
  throw new Error(`读取/解析 ${pkgPath} 失败：${String(error)}`, { cause: error });
}
if (typeof pkgJson !== "object" || pkgJson === null || Array.isArray(pkgJson)) {
  throw new TypeError(`${pkgPath} 的顶层不是 JSON 对象`);
}

/**
 * 官方 client bundle 的**隐式 external 基座**：外壳预置的冻结模块表（`PLATFORM_MODULES`）
 * 加 parser 预载行（`PRELOADED_CLIENT_EXTERNALS`，当前为空）。两份真源都在
 * @deepseek-ai/dsh-client-web 的 `src/platform.ts`，而官方 client 构建器
 * `packages/client/tsdown.client.ts` 的 `clientExternals()` 算的就是「基座 ∪ 本包
 * dsh.client.external」——同文件注释明写 "The shell baseline is implicit for every
 * dynamic bundle"。基座里每一枚都必须 external：内联一份 react / cordis / UI 库的副本
 * 就是同一个模块两份身份（宿主只认模块表那一条），基座里漏一枚就是少一份外部化。
 * test/build-client.test.ts 把清单逐条钉住，改这里之前先看官方那两份真源动没动。
 * @type {readonly string[]}
 */
const CLIENT_BASELINE = [
  "react",
  "react/jsx-runtime",
  "react-dom",
  "react-dom/client",
  "@deepseek-ai/cordis",
  "@deepseek-ai/dsh-client-store",
  "@deepseek-ai/dsh-client-ui-slots",
  "@deepseek-ai/dsh-client-ui-primitives",
  "@deepseek-ai/dsh-client-ui-dockkit",
];

/** 本包 `dsh.client.external` 声明的基座之外请求（缺省 = 只有基座，本包当前如此）。
 *  官方口径是"精确串匹配、不归一"（tsdown.client.ts 的 requestedExternals 注释），
 *  故这里原样收：不裁剪、不排序、不合并重复。 */
function declaredClientExternals() {
  const { dsh } = asRecord(pkgJson);
  const { client } = asRecord(dsh);
  const { external } = asRecord(client);
  if (external === undefined) {
    return [];
  }
  if (!Array.isArray(external)) {
    // 声明形态错误（写成单个字符串/对象）静默吞掉 = 基座之外少外置一枚模块，表现为
    // 运行期"模块表里没有这一条"，而构建日志毫无信号——声明坏了就响亮失败。
    throw new TypeError(
      `package.json 的 dsh.client.external 必须是字符串数组，实际是 ${typeof external}`,
    );
  }
  const declared = [];
  for (const [index, item] of external.entries()) {
    if (typeof item !== "string") {
      throw new TypeError(
        `package.json 的 dsh.client.external[${String(index)}] 必须是字符串，实际是 ${typeof item}`,
      );
    }
    declared.push(item);
  }
  return declared;
}

/**
 * 本包 client bundle 的 external 清单（构建与测试同源）：官方基座 + 本包声明。
 * @returns {string[]} 需要保持外部的模块说明符。
 */
export function clientExternals() {
  return [...CLIENT_BASELINE, ...declaredClientExternals()];
}

/** 生成头的前缀（写盘自检判据；tests 里钉的是同一句）。 */
const GENERATED_PREFIX = "// GENERATED by buildClient() in build-client.mjs";

/** 生成 client.js 的完整文本（含 ModuleLoader 外壳）。 */
export async function buildClient() {
  return buildClientBundle({
    root,
    rolldown,
    externals: clientExternals(),
    header: `${GENERATED_PREFIX} — edit src/*.ts, then run \`node build-client.mjs\`.`,
  });
}

async function main() {
  const out = await buildClient();
  // 与 build-host 同款写盘自检：不把上一份可用产物换成不可用内容还退 0。
  if (out.length === 0 || !out.startsWith(GENERATED_PREFIX)) {
    throw new Error("client.js 构建产物异常（空正文或缺生成头），已放弃写盘");
  }
  await writeArtifact(path.join(root, "client.js"), out);
  console.info("client.js written:", Buffer.byteLength(out, "utf8"), "bytes");
}

if (invokedDirectly(import.meta.filename)) {
  try {
    await main();
  } catch (error) {
    console.error(error);
    process.exitCode = 1;
  }
}
